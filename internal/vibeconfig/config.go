// Package vibeconfig writes the Mistral Vibe CLI's TOML config: the
// session-local file the sandbox mounts, and the managed block rnes keeps in
// the user's own config on the host.
package vibeconfig

import (
	"bytes"
	"fmt"
	"strings"
	"unicode/utf8"

	"github.com/BurntSushi/toml"

	"github.com/df3l0p/rnes/internal/configfile"
)

const (
	// ProviderName is the provider block rnes adds for the session's
	// llama-server. It is deliberately not "llamacpp" (the name a user's own
	// local provider tends to have) so rnes never shadows or duplicates one.
	ProviderName = "rnes-llamacpp"

	// blockStart and blockEnd delimit the managed block in the user's config.
	// Everything between them belongs to rnes and is replaced on every run;
	// the rest of the file is left exactly as it was.
	blockStart = "# >>> rnes: local llama-server (managed by rnes; edits here are overwritten)"
	blockEnd   = "# <<< rnes"
)

// Render returns the whole config for a sandbox session: the local
// llama-server provider, one model per served model, and the served model as
// the default. It is generated from scratch rather than copied from the host
// config, so nothing the user's own config.toml holds (an MCP server's static
// header, a provider's extra_headers) can reach the container.
//
// Telemetry, update checks, auto-update, experiments and connectors are off:
// the sandbox's egress is allow-listed and audited, and none of them is
// something the agent needs to do its work. Connectors matter most: with
// RNES_MISTRAL_API_KEY set, Vibe would otherwise offer the operator's own
// Mistral connectors (Drive, GitHub, Linear, Slack) to the agent.
//
// Vibe merges this over its built-in defaults rather than replacing them, so
// its own mistral and llamacpp providers survive, and a project
// .vibe/config.toml can still override any of these switches. The sandbox's
// egress proxy, not this file, is what actually bounds the session.
func Render(baseURL string, modelIDs []string) ([]byte, error) {
	if err := checkModelIDs(modelIDs); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Generated by rnes for this sandbox session: the local llama-server\n")
	b.WriteString("# provider and the models it serves. Nothing here is read from your own\n")
	b.WriteString("# config.toml, so no host credential reaches the container.\n")
	b.WriteString("enable_telemetry = false\n")
	b.WriteString("enable_update_checks = false\n")
	b.WriteString("enable_auto_update = false\n")
	b.WriteString("enable_connectors = false\n")
	if len(modelIDs) > 0 {
		fmt.Fprintf(&b, "active_model = %s\n", quote(modelIDs[0]))
	}
	b.WriteString("\n")
	b.WriteString("[experiments]\n")
	b.WriteString("enable = false\n\n")
	b.WriteString(providerBlock(baseURL))
	b.WriteString(modelsBlock(modelIDs))
	return []byte(b.String()), nil
}

// Merge replaces rnes's managed block in the config at path with one pointing
// at baseURL, creating the file (and its directory) when missing. Everything
// outside the block is preserved, including comments; the block is kept last
// in the file and the blank lines around it are normalised. The user's
// active_model is never touched: on the host the session's model is pinned
// through VIBE_ACTIVE_MODEL instead, which outlives nothing.
//
// The file is parsed before and after the edit, so a config rnes can't read is
// left untouched rather than half-rewritten, and a block that would not parse
// is never written. The read-modify-write goes through configfile.Update, so a
// concurrent rnes process can't drop this one's change and a crash mid-write
// can't leave the config truncated.
func Merge(path, baseURL string, modelIDs []string) error {
	if err := checkModelIDs(modelIDs); err != nil {
		return err
	}
	block := managedBlock(baseURL, modelIDs)
	return configfile.Update(path, func(raw []byte) ([]byte, error) {
		if err := checkTOML(raw); err != nil {
			return nil, fmt.Errorf("parsing: %w", err)
		}
		out := mergeBlock(raw, block)
		if err := checkTOML(out); err != nil {
			return nil, fmt.Errorf("parsing the merged config: %w", err)
		}
		return out, nil
	})
}

// checkTOML reports whether raw is valid TOML, so rnes never writes into a
// config Vibe itself would refuse to load. An empty file is valid.
func checkTOML(raw []byte) error {
	if len(bytes.TrimSpace(raw)) == 0 {
		return nil
	}
	var parsed map[string]any
	return toml.Unmarshal(raw, &parsed)
}

// checkModelIDs rejects ids quote can't render faithfully: a model id that
// isn't valid UTF-8 would otherwise reach the config as U+FFFD and name a model
// llama-server doesn't serve.
func checkModelIDs(modelIDs []string) error {
	for _, id := range modelIDs {
		if !utf8.ValidString(id) {
			return fmt.Errorf("model id %q is not valid UTF-8", id)
		}
	}
	return nil
}

// SetModel makes the config in raw start on alias, replacing the active_model
// line Render wrote. It is how a sandbox session starts on the model rnes
// serves without the config outliving the session.
func SetModel(raw []byte, alias string) ([]byte, error) {
	if !utf8.ValidString(alias) {
		return nil, fmt.Errorf("model id %q is not valid UTF-8", alias)
	}
	line := "active_model = " + quote(alias)
	lines := strings.Split(string(raw), "\n")
	inTable := false
	for i, l := range lines {
		trimmed := strings.TrimSpace(l)
		if strings.HasPrefix(trimmed, "[") {
			inTable = true
		}
		if !inTable && isActiveModel(l) {
			lines[i] = line
			return []byte(strings.Join(lines, "\n")), nil
		}
	}
	return []byte(line + "\n" + string(raw)), nil
}

// isActiveModel reports whether a config line sets the top-level active_model
// key (and not, say, a key that merely starts with the same word).
func isActiveModel(line string) bool {
	rest, ok := strings.CutPrefix(strings.TrimSpace(line), "active_model")
	if !ok {
		return false
	}
	rest = strings.TrimLeft(rest, " \t")
	return strings.HasPrefix(rest, "=")
}

// managedBlock is the block Merge keeps in the user's config: the provider and
// its models, without an active_model line.
func managedBlock(baseURL string, modelIDs []string) string {
	return blockStart + "\n" + providerBlock(baseURL) + modelsBlock(modelIDs) + blockEnd + "\n"
}

// mergeBlock returns raw with any previous managed block replaced by block.
func mergeBlock(raw []byte, block string) []byte {
	text := strings.TrimRight(stripBlock(string(raw)), "\n")
	if text == "" {
		return []byte(block)
	}
	return []byte(text + "\n\n" + block)
}

// stripBlock removes every managed block from text, including one left
// unterminated by a hand edit (everything from its start to the end of the
// file). Markers only count as a whole line, so a model id or a comment that
// happens to contain one can't be mistaken for the block's edge.
func stripBlock(text string) string {
	for {
		start := findMarker(text, blockStart, 0)
		if start < 0 {
			return text
		}
		end := findMarker(text, blockEnd, start+len(blockStart))
		if end < 0 {
			return text[:start]
		}
		text = text[:start] + text[end+len(blockEnd):]
	}
}

// findMarker returns the offset of marker in text at or after from, counting
// only occurrences that make up a whole line.
func findMarker(text, marker string, from int) int {
	for from <= len(text) {
		i := strings.Index(text[from:], marker)
		if i < 0 {
			return -1
		}
		i += from
		if (i == 0 || text[i-1] == '\n') && restOfLineBlank(text[i+len(marker):]) {
			return i
		}
		from = i + 1
	}
	return -1
}

// restOfLineBlank reports whether the text up to the next newline is blank.
func restOfLineBlank(rest string) bool {
	if i := strings.IndexByte(rest, '\n'); i >= 0 {
		rest = rest[:i]
	}
	return strings.TrimSpace(rest) == ""
}

// providerBlock is the provider entry pointing Vibe at a llama-server.
// api_key_env_var is empty: llama-server takes no key, and the sandbox's
// egress proxy is what authenticates anything that needs it.
func providerBlock(baseURL string) string {
	var b strings.Builder
	b.WriteString("[[providers]]\n")
	fmt.Fprintf(&b, "name = %s\n", quote(ProviderName))
	fmt.Fprintf(&b, "api_base = %s\n", quote(strings.TrimRight(baseURL, "/")+"/v1"))
	b.WriteString("api_key_env_var = \"\"\n\n")
	return b.String()
}

// modelsBlock is one model entry per served model, each aliased to its own id
// so /model lists them under the names llama-server reports.
func modelsBlock(modelIDs []string) string {
	var b strings.Builder
	for _, id := range modelIDs {
		b.WriteString("[[models]]\n")
		fmt.Fprintf(&b, "name = %s\n", quote(id))
		fmt.Fprintf(&b, "provider = %s\n", quote(ProviderName))
		fmt.Fprintf(&b, "alias = %s\n\n", quote(id))
	}
	return b.String()
}

// quote renders s as a TOML basic string, so a model id with a quote or a
// backslash still means what it says.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
