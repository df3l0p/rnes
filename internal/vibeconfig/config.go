// Package vibeconfig writes the Mistral Vibe CLI's TOML config: the
// session-local file the sandbox mounts, and the managed block rnes keeps in
// the user's own config on the host.
package vibeconfig

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"syscall"
)

const (
	// ProviderName is the provider block rnes adds for the session's
	// llama-server. It is deliberately not "llamacpp" (the name a user's own
	// local provider tends to have) so rnes never shadows or duplicates one.
	ProviderName = "rnes-llamacpp"

	// blockStart and blockEnd delimit the managed block in the user's config.
	// Everything between them belongs to rnes and is replaced on every run;
	// the rest of the file is left exactly as it was.
	blockStart = "# >>> rnes: local llama-server (managed by rnes; edits here are overwritten)"
	blockEnd   = "# <<< rnes"
)

// Render returns the whole config for a sandbox session: the local
// llama-server provider, one model per served model, and the served model as
// the default. It is generated from scratch rather than copied from the host
// config, so nothing the user's own config.toml holds (an MCP server's static
// header, a provider's extra_headers) can reach the container.
//
// Telemetry, update checks and auto-update are off: the sandbox's egress is
// allow-listed and audited, and none of the three is something the agent
// needs to do its work.
func Render(baseURL string, modelIDs []string) []byte {
	var b strings.Builder
	b.WriteString("# Generated by rnes for this sandbox session: the local llama-server\n")
	b.WriteString("# provider and the models it serves. Nothing here is read from your own\n")
	b.WriteString("# config.toml, so no host credential reaches the container.\n")
	b.WriteString("enable_telemetry = false\n")
	b.WriteString("enable_update_checks = false\n")
	b.WriteString("enable_auto_update = false\n")
	if len(modelIDs) > 0 {
		fmt.Fprintf(&b, "active_model = %s\n", quote(modelIDs[0]))
	}
	b.WriteString("\n")
	b.WriteString(providerBlock(baseURL))
	b.WriteString(modelsBlock(modelIDs))
	return []byte(b.String())
}

// Merge replaces rnes's managed block in the config at path with one pointing
// at baseURL, creating the file (and its directory) when missing. Everything
// outside the block is preserved byte for byte, including comments, and the
// user's active_model is never touched: on the host the session starts on
// whatever model Vibe would pick anyway, and the llama-server models are one
// /model selection away.
//
// The read-modify-write is guarded by an flock on a sibling ".lock" file, so
// two rnes processes racing on the same config don't silently drop one
// another's changes, and the write goes through a temp file + rename so a
// crash mid-write can't leave the config truncated.
func Merge(path, baseURL string, modelIDs []string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}

	lock, err := os.OpenFile(path+".lock", os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return fmt.Errorf("opening lock file: %w", err)
	}
	defer lock.Close()
	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_EX); err != nil {
		return fmt.Errorf("locking %s: %w", path, err)
	}
	defer syscall.Flock(int(lock.Fd()), syscall.LOCK_UN)

	raw, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	mode := os.FileMode(0o644)
	if fi, err := os.Stat(path); err == nil {
		mode = fi.Mode().Perm()
	}
	out := mergeBlock(raw, managedBlock(baseURL, modelIDs))

	tmp, err := os.CreateTemp(dir, ".rnes-vibe-config-*.tmp")
	if err != nil {
		return fmt.Errorf("creating temp file in %s: %w", dir, err)
	}
	tmpPath := tmp.Name()
	defer os.Remove(tmpPath) // no-op once the rename below succeeds

	if _, err := tmp.Write(out); err != nil {
		tmp.Close()
		return fmt.Errorf("writing %s: %w", tmpPath, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("closing %s: %w", tmpPath, err)
	}
	if err := os.Chmod(tmpPath, mode); err != nil {
		return fmt.Errorf("setting permissions on %s: %w", tmpPath, err)
	}
	if err := os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("replacing %s: %w", path, err)
	}
	return nil
}

// SetModel makes the config in raw start on alias, replacing the active_model
// line Render wrote. It is how a sandbox session starts on the model rnes
// serves without the config outliving the session.
func SetModel(raw []byte, alias string) ([]byte, error) {
	line := "active_model = " + quote(alias)
	lines := strings.Split(string(raw), "\n")
	for i, l := range lines {
		if isActiveModel(l) {
			lines[i] = line
			return []byte(strings.Join(lines, "\n")), nil
		}
	}
	return []byte(line + "\n" + string(raw)), nil
}

// isActiveModel reports whether a config line sets the top-level active_model
// key (and not, say, a key that merely starts with the same word).
func isActiveModel(line string) bool {
	rest, ok := strings.CutPrefix(strings.TrimSpace(line), "active_model")
	if !ok {
		return false
	}
	rest = strings.TrimLeft(rest, " \t")
	return strings.HasPrefix(rest, "=")
}

// managedBlock is the block Merge keeps in the user's config: the provider and
// its models, without an active_model line.
func managedBlock(baseURL string, modelIDs []string) string {
	return blockStart + "\n" + providerBlock(baseURL) + modelsBlock(modelIDs) + blockEnd + "\n"
}

// mergeBlock returns raw with any previous managed block replaced by block.
func mergeBlock(raw []byte, block string) []byte {
	text := strings.TrimRight(stripBlock(string(raw)), "\n")
	if text == "" {
		return []byte(block)
	}
	return []byte(text + "\n\n" + block)
}

// stripBlock removes the managed block from text, including a block left
// unterminated by a hand edit (everything from its start to the end of the
// file).
func stripBlock(text string) string {
	start := strings.Index(text, blockStart)
	if start < 0 {
		return text
	}
	end := strings.Index(text[start:], blockEnd)
	if end < 0 {
		return text[:start]
	}
	return text[:start] + text[start+end+len(blockEnd):]
}

// providerBlock is the provider entry pointing Vibe at a llama-server.
// api_key_env_var is empty: llama-server takes no key, and the sandbox's
// egress proxy is what authenticates anything that needs it.
func providerBlock(baseURL string) string {
	var b strings.Builder
	b.WriteString("[[providers]]\n")
	fmt.Fprintf(&b, "name = %s\n", quote(ProviderName))
	fmt.Fprintf(&b, "api_base = %s\n", quote(strings.TrimRight(baseURL, "/")+"/v1"))
	b.WriteString("api_key_env_var = \"\"\n\n")
	return b.String()
}

// modelsBlock is one model entry per served model, each aliased to its own id
// so /model lists them under the names llama-server reports.
func modelsBlock(modelIDs []string) string {
	var b strings.Builder
	for _, id := range modelIDs {
		b.WriteString("[[models]]\n")
		fmt.Fprintf(&b, "name = %s\n", quote(id))
		fmt.Fprintf(&b, "provider = %s\n", quote(ProviderName))
		fmt.Fprintf(&b, "alias = %s\n\n", quote(id))
	}
	return b.String()
}

// quote renders s as a TOML basic string, so a model id with a quote or a
// backslash still means what it says.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
